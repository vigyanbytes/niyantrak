"""As-built documents from facts: node cards and the join store → Markdown + HTML pages and an SVG network map.

    pages = render(collect(join.load(store), local={"card": card.collect(), "checks": [...]}))
    write("<state root>/docs", pages)        # returns the files that changed; same input → byte-identical files

Output: index.md/.html (fleet overview), node-<node id>.md/.html (hardware, OS, addresses, roles, governance
checks), network-map.svg, manifest.json. No timestamps of generation, every list sorted, so a regenerate with
the same facts rewrites nothing. Card text comes from other machines and is untrusted: it is escaped in HTML,
SVG and Markdown. SSH host keys and token hashes are never written (keys as a sha256 only).
"""
import hashlib
import html
import ipaddress
import json
import os
import re

from ..decisions.schema import SECRET_PATTERNS

TITLE = "Fleet as built"
INTRO = ("Generated by Niyantrak from signed node cards and the join store. The same facts always give the same "
         "files: there is no generation timestamp, so a page changes only when a machine changes.")
STATE_COLOURS = {"this machine": "#1d4ed8", "approved": "#15803d", "pending": "#b45309", "rejected": "#b91c1c"}
CSS = """:root{--bg:#faf6ee;--card:#fff;--ink:#1c1814;--body:#3a332b;--muted:#6b6357;--line:rgba(28,24,20,.14);--link:#9a4f08}
@media (prefers-color-scheme:dark){:root{--bg:#020617;--card:#0f172a;--ink:#f8fafc;--body:#cbd5e1;--muted:#94a3b8;--line:rgba(255,255,255,.12);--link:#fbbf24}}
body{margin:0;background:var(--bg);color:var(--body);font:14px/1.55 Inter,system-ui,sans-serif}
main{max-width:980px;margin:0 auto;padding:24px 16px}h1{color:var(--ink);font-size:22px;margin:0 0 8px}
h2{color:var(--ink);font-size:16px;margin:24px 0 8px}a{color:var(--link)}p.muted{color:var(--muted)}
.wrap{overflow-x:auto}table{border-collapse:collapse;width:100%;background:var(--card);font-size:13px}
th,td{text-align:left;padding:6px 8px;border-bottom:1px solid var(--line);vertical-align:top}
th{font-size:11px;letter-spacing:.06em;text-transform:uppercase;color:var(--muted)}
code{font-family:"JetBrains Mono",ui-monospace,monospace;font-size:12.5px}svg{max-width:100%;height:auto}
"""


# ── inputs ──────────────────────────────────────────────────────────────────────────────────────────────
def _node(card, **extra):
    card = card if isinstance(card, dict) else {}
    osd = card.get("os") if isinstance(card.get("os"), dict) else {}
    addr = card.get("addresses") if isinstance(card.get("addresses"), dict) else {}
    gpus = [g for g in card.get("gpu") or [] if isinstance(g, dict)]
    return {"node_id": str(card.get("node_id") or ""), "hostname": str(card.get("hostname") or card.get("node_id") or "?"),
            "role": card.get("role"), "os": " ".join(str(x) for x in (osd.get("id"), osd.get("version")) if x) or None,
            "kernel": osd.get("kernel"), "arch": osd.get("arch"), "cores": (card.get("cpu") or {}).get("cores"),
            "memory_gb": card.get("memory_gb"),
            "gpu": sorted(f"{g.get('name', '?')}" + (f" ({round(g['vram_mb'] / 1024)} GB)" if g.get("vram_mb") else "") for g in gpus),
            "ipv4": sorted(str(a) for a in addr.get("ipv4") or []), "ipv6": sorted(str(a) for a in addr.get("ipv6") or []),
            "card_sha256": hashlib.sha256(json.dumps(card, sort_keys=True, separators=(",", ":")).encode()).hexdigest(),
            "host_key_sha256": None, "checks": [], "decided_by": None, "decided_at": None, "requested_at": None, **extra}


def collect(join_store, local=None):
    """Nodes for the documents: this machine first (when given), then every machine in the join store by node id."""
    nodes, seen = [], set()
    if local and isinstance(local.get("card"), dict):
        n = _node(local["card"], state="this machine", source="this machine",
                  checks=[{"name": str(c.get("name")), "ok": bool(c.get("ok"))} for c in local.get("checks") or []])
        nodes.append(n)
        seen.add(n["node_id"])
    joined = (join_store or {}).get("nodes") or {}
    for nid in sorted(joined):
        rec = joined[nid]
        if nid in seen or not re.fullmatch(r"nyk-[0-9a-f]{1,64}", str(nid)):
            continue
        pub = " ".join(str(rec.get("host_pubkey") or "").split()[:2])
        n = _node(rec.get("card"), state=str(rec.get("state") or "pending"), source="joined",
                  decided_by=rec.get("decided_by"), decided_at=rec.get("decided_at"), requested_at=rec.get("requested_at"),
                  host_key_sha256=hashlib.sha256(pub.encode()).hexdigest() if pub else None)
        n["node_id"] = nid                                   # the store's key is authoritative
        if rec.get("card_sha256"):
            n["card_sha256"] = str(rec["card_sha256"])
        nodes.append(n)
    return {"nodes": nodes}


# ── page model → Markdown / HTML ────────────────────────────────────────────────────────────────────────
def _md_cell(v):
    s = "—" if v in (None, "", []) else str(v)
    s = html.escape(s, quote=False).replace("|", "\\|")
    return re.sub(r"\s+", " ", s)


def _md_link(text, href):
    return ("link", text, href)


def to_md(title, blocks):
    out = [f"# {_md_cell(title)}", ""]
    for b in blocks:
        if b[0] == "h":
            out += [f"## {b[1]}", ""]
        elif b[0] == "p":
            out += [_md_cell(b[1]), ""]
        elif b[0] == "img":
            out += [f"![{b[1]}]({b[2]})", ""]
        elif b[0] == "table":
            head, rows = b[1], b[2]
            if not rows:
                out += ["_none recorded_", ""]
                continue
            cell = lambda c: f"[{_md_cell(c[1])}]({c[2]})" if isinstance(c, tuple) else _md_cell(c)
            out += ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
            out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows] + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def to_html(title, blocks, svg=None, back=True):
    e = lambda v: html.escape("—" if v in (None, "", []) else str(v))
    out = ["<!doctype html>", '<html lang="en">', "<head>", '<meta charset="utf-8">',
           '<meta name="viewport" content="width=device-width,initial-scale=1">', f"<title>{e(title)}</title>",
           f"<style>\n{CSS}</style>", "</head>", "<body>", "<main>"]
    if back:
        out.append('<p><a href="index.html">← Fleet as built</a></p>')
    out.append(f"<h1>{e(title)}</h1>")
    for b in blocks:
        if b[0] == "h":
            out.append(f"<h2>{e(b[1])}</h2>")
        elif b[0] == "p":
            out.append(f"<p>{e(b[1])}</p>")
        elif b[0] == "img":
            out.append(svg if svg else f'<p><a href="{e(b[2])}">{e(b[1])}</a></p>')
        elif b[0] == "table":
            if not b[2]:
                out.append('<p class="muted">none recorded</p>')
                continue
            cell = lambda c: f'<a href="{e(c[2].replace(".md", ".html"))}">{e(c[1])}</a>' if isinstance(c, tuple) else e(c)
            out.append('<div class="wrap"><table><thead><tr>' + "".join(f"<th>{e(h)}</th>" for h in b[1]) + "</tr></thead><tbody>")
            out += ["<tr>" + "".join(f"<td>{cell(c)}</td>" for c in r) + "</tr>" for r in b[2]]
            out.append("</tbody></table></div>")
    out += ["</main>", "</body>", "</html>"]
    return "\n".join(out) + "\n"


def _page_name(n):
    return "node-" + re.sub(r"[^A-Za-z0-9_-]", "_", n["node_id"])


def _gb(v):
    return None if v in (None, "") else f"{v} GB"


def _checks_passing(n):
    return f"{sum(c['ok'] for c in n['checks'])} / {len(n['checks'])}" if n["checks"] else None


def fleet_blocks(nodes):
    if not nodes:
        return [("p", INTRO), ("p", "No machines recorded yet. Approve machines under Fleet in the panel, then regenerate.")]
    counts = {}
    for n in nodes:
        counts[n["state"]] = counts.get(n["state"], 0) + 1
    summary = f"{len(nodes)} machine(s): " + ", ".join(f"{v} {k}" for k, v in sorted(counts.items())) + "."
    machines = [[n["hostname"], n["node_id"], n["state"], n["role"], n["os"], n["cores"], _gb(n["memory_gb"]),
                 ", ".join(n["gpu"]), ", ".join(n["ipv4"] + n["ipv6"]), _md_link("details", _page_name(n) + ".md")] for n in nodes]
    gov = [[n["hostname"], n["state"], n["decided_by"], n["decided_at"], _checks_passing(n)] for n in nodes]
    return [("p", INTRO), ("p", summary),
            ("h", "Machines"), ("table", ["host", "node id", "state", "role", "os", "cpu cores", "memory", "gpu", "addresses", "page"], machines),
            ("h", "Network map"), ("img", "Network map", "network-map.svg"),
            ("h", "Governance"), ("table", ["host", "state", "decided by", "decided at", "checks passing"], gov)]


def node_blocks(n):
    hw = [["cpu cores", n["cores"]], ["memory", _gb(n["memory_gb"])], ["gpu", ", ".join(n["gpu"]) or "none"], ["architecture", n["arch"]]]
    osr = [["operating system", n["os"]], ["kernel", n["kernel"]]]
    addrs = [["IPv4", a] for a in n["ipv4"]] + [["IPv6", a] for a in n["ipv6"]]
    gov = [["join state", n["state"]]]
    if n["source"] == "joined":
        gov += [["card signature verified at join", "yes (the join store records only verified cards)"],
                ["requested at", n["requested_at"]], ["decided by", n["decided_by"]], ["decided at", n["decided_at"]],
                ["host key sha256", n["host_key_sha256"]]]
    gov += [["card sha256", n["card_sha256"]]]
    gov += [[c["name"], "PASS" if c["ok"] else "FAIL"] for c in n["checks"]]
    return [("p", f"Node {n['node_id']} · {n['source']}."),
            ("h", "Hardware"), ("table", ["fact", "value"], hw),
            ("h", "Operating system"), ("table", ["fact", "value"], osr),
            ("h", "Addresses"), ("table", ["family", "address"], addrs),
            ("h", "Roles"), ("table", ["role", "source"], [[n["role"], "node card"]] if n["role"] else []),
            ("h", "Governance checks"), ("table", ["check", "result"], gov)]


# ── network map ─────────────────────────────────────────────────────────────────────────────────────────
def network_of(n):
    for a in n["ipv4"]:
        try:
            return str(ipaddress.ip_network(f"{a}/24", strict=False))
        except ValueError:
            continue
    for a in n["ipv6"]:
        try:
            ip = ipaddress.ip_address(a.split("%", 1)[0])
        except ValueError:
            continue
        if not ip.is_link_local:
            return str(ipaddress.ip_network(f"{ip}/64", strict=False))
    return "IPv6 link-local only" if n["ipv6"] else "no address"


def network_svg(nodes):
    groups = {}
    for n in nodes:
        groups.setdefault(network_of(n), []).append(n)
    names = sorted(groups)
    col, gap, pad, row = 220, 24, 20, 56
    e = lambda s: html.escape(str(s))
    width = max(pad * 2 + len(names) * col + max(len(names) - 1, 0) * gap, 360)
    tallest = max((len(v) for v in groups.values()), default=0)
    box_h = 44 + tallest * row
    height = 70 + box_h + 60
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
           'role="img" aria-label="Network map" font-family="Inter, system-ui, sans-serif" font-size="12">',
           f'<rect width="{width}" height="{height}" fill="#ffffff"/>',
           f'<text x="{pad}" y="24" font-size="14" font-weight="700" fill="#1c1814">Network map</text>']
    if not names:
        out.append(f'<text x="{pad}" y="60" fill="#6b6357">No machines recorded yet.</text>')
    else:
        out.append(f'<line x1="{pad + col // 2}" y1="44" x2="{pad + (len(names) - 1) * (col + gap) + col // 2}" y2="44" '
                   'stroke="#6b6357" stroke-width="2"/>')
    for i, name in enumerate(names):
        x = pad + i * (col + gap)
        out += [f'<line x1="{x + col // 2}" y1="44" x2="{x + col // 2}" y2="60" stroke="#6b6357" stroke-width="2"/>',
                f'<rect x="{x}" y="60" width="{col}" height="{box_h}" rx="8" fill="#f7f2e7" stroke="#d6cfc2"/>',
                f'<text x="{x + 10}" y="80" font-weight="600" fill="#1c1814">{e(name)}</text>']
        for j, n in enumerate(sorted(groups[name], key=lambda n: (n["hostname"], n["node_id"]))):
            y = 92 + j * row
            colour = STATE_COLOURS.get(n["state"], "#57534e")
            addr = (n["ipv4"] + [a for a in n["ipv6"] if not a.startswith("fe80")] + n["ipv6"] + ["—"])[0]
            out += [f'<rect x="{x + 10}" y="{y}" width="{col - 20}" height="44" rx="6" fill="#ffffff" stroke="{colour}" stroke-width="2"/>',
                    f'<text x="{x + 20}" y="{y + 18}" font-weight="600" fill="#1c1814">{e(n["hostname"][:28])}</text>',
                    f'<text x="{x + 20}" y="{y + 34}" fill="#3a332b">{e(addr[:30])} · {e(n["state"])}</text>']
    ly = 70 + box_h + 30
    for k, (state, colour) in enumerate(STATE_COLOURS.items()):
        lx = pad + k * 110
        out += [f'<rect x="{lx}" y="{ly - 10}" width="12" height="12" rx="3" fill="{colour}"/>',
                f'<text x="{lx + 18}" y="{ly}" fill="#3a332b">{e(state)}</text>']
    out.append("</svg>")
    return "\n".join(out) + "\n"


# ── render / write ──────────────────────────────────────────────────────────────────────────────────────
def leaks(text):
    return [p.pattern[:30] for p in SECRET_PATTERNS if p.search(text)] + (["home path"] if re.search(r"/home/[a-z]", text) else [])


def render(inputs):
    nodes = inputs.get("nodes") or []
    svg = network_svg(nodes)
    fb = fleet_blocks(nodes)
    pages = {"index.md": to_md(TITLE, fb), "index.html": to_html(TITLE, fb, svg=svg, back=False), "network-map.svg": svg}
    listing = [{"file": "index.html", "md": "index.md", "title": TITLE, "kind": "fleet"},
               {"file": "network-map.svg", "md": None, "title": "Network map", "kind": "map"}]
    for n in sorted(nodes, key=lambda n: n["node_id"]):
        name, blocks = _page_name(n), node_blocks(n)
        pages[name + ".md"] = to_md(n["hostname"], blocks)
        pages[name + ".html"] = to_html(n["hostname"], blocks)
        listing.append({"file": name + ".html", "md": name + ".md", "title": n["hostname"], "kind": "node"})
    files = sorted(list(pages) + ["manifest.json"])
    pages["manifest.json"] = json.dumps({"generator": "niyantrak docs", "version": 1, "pages": listing, "files": files},
                                        indent=1, sort_keys=True) + "\n"
    found = sorted({x for body in pages.values() for x in leaks(body)})
    if found:
        raise ValueError(f"refusing to write documents: possible secret or personal path ({', '.join(found)})")
    return dict(sorted(pages.items()))


def write(out_dir, pages):
    """Write changed files only (atomic), remove files a previous run generated that are gone now. Returns changed."""
    os.makedirs(out_dir, exist_ok=True)
    old = set()
    try:
        with open(os.path.join(out_dir, "manifest.json")) as f:
            old = set(json.load(f).get("files") or [])
    except (OSError, ValueError):
        pass
    changed = []
    for name, body in pages.items():
        path, data = os.path.join(out_dir, name), body.encode()
        try:
            with open(path, "rb") as f:
                if f.read() == data:
                    continue
        except OSError:
            pass
        with open(path + ".tmp", "wb") as f:
            f.write(data)
        os.replace(path + ".tmp", path)
        changed.append(name)
    for name in sorted(old - set(pages)):
        if "/" not in name and os.path.isfile(os.path.join(out_dir, name)):
            os.unlink(os.path.join(out_dir, name))
    return sorted(changed)


def list_pages(out_dir):
    try:
        with open(os.path.join(out_dir, "manifest.json")) as f:
            return json.load(f).get("pages") or []
    except (OSError, ValueError):
        return []


def default_dir():
    from ..paths import state_root
    return os.environ.get("NIYANTRAK_DOCS") or os.path.join(state_root(), "docs")


def generate(out_dir=None, join_store=None, local=None):
    """Regenerate from the join store file (and this machine's card/checks when given)."""
    from .. import join as joinmod
    pages = render(collect(joinmod.load(join_store or joinmod.STORE), local=local))
    return write(out_dir or default_dir(), pages)
