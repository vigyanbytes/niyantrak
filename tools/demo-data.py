def fleet(end):
    def card(host, role, os_, v4, v6):
        return {"node_id": node_id(host), "hostname": host, "role": role, "os": os_, "ipv4": [v4], "ipv6": [v6] if v6 else []}
    checks = [{"name": n, "ok": True} for n in ("Audit rules record sensitive changes",
                                                 "Remote login hardened (keys only, no root)",
                                                 "Secrets folder private", "Login status page installed")]
    node = {**card(*FLEET[0]), "bootstrapped": True, "checks": checks}
    peers = {}
    for i, f in enumerate(FLEET[1:]):
        p = card(*f)
        peers[p["node_id"]] = {**p, "verified": i != 4, "seen_at": f"{i + 1} min ago"}
    host, role, os_, v4, _ = PENDING
    os_id, os_ver = os_.split(" ", 1)
    joins = {node_id(host): {"node_id": node_id(host), "state": "pending", "requested_at": f"{end}T09:12:00Z",
                             "card_sha256": hashlib.sha256(host.encode()).hexdigest(),
                             "card": {"hostname": host, "role": role, "os": {"id": os_id, "version": os_ver},
                                      "addresses": {"ipv4": [v4], "ipv6": []}}}}
    return node, peers, joins


def build(out, end, days=14, seed=7):
    from niyantrak.decisions import graph
    from niyantrak.decisions.store import Store as DecisionStore
    from niyantrak.telemetry.store import Store
    ev, dec = events(end, days, seed), decisions(end)
    for sub in ("telemetry", "decisions"):
        shutil.rmtree(os.path.join(out, sub), ignore_errors=True)
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "events.json"), "w") as f:
        json.dump(ev, f, indent=1, sort_keys=True)
        f.write("\n")
    with open(os.path.join(out, "decisions.jsonl"), "w") as f:
        f.writelines(json.dumps(r, sort_keys=True) + "\n" for r in dec)
    st = Store(os.path.join(out, "telemetry"), writer="demo")
    st.append(ev)
    ds = DecisionStore(os.path.join(out, "decisions"))
    ds.append(dec, writer="demo-data", env={})
    now = datetime.combine(end, time(23, 0), timezone.utc)
    node, peers, joins = fleet(end)
    counts = {}
    for e in ev:
        for k, n in e["entity_counts"].items():
            counts[k] = counts.get(k, 0) + n
    bundle = {"label": LABEL, "end": str(end), "days": days, "seed": seed, "events": len(ev),
              "activity": st.activity(days=7, now=now), "decisions": graph.export_graph(graph.derive(ds.events())),
              "node": node, "peers": peers, "joins": joins,
              "counts": dict(sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))}
    filters = {(n["col"], n["value"]) for n in bundle["activity"]["sankey"]["nodes"] if n["value"] is not None}
    filters |= {("why", w["name"]) for w in bundle["activity"]["why"]}
    bundle["activity_by"] = {f"{k}={v}": st.activity(days=7, now=now, filter=(k, v)) for k, v in sorted(filters)}
    for a in [bundle["activity"], *bundle["activity_by"].values()]:
        a["sample"] = LABEL
    with open(os.path.join(out, "bundle.json"), "w") as f:
        json.dump(bundle, f, indent=1, sort_keys=True, default=str)
        f.write("\n")
    return bundle


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=os.path.join(ROOT, "dist", "demo"))
    ap.add_argument("--end", default=str(datetime.now(timezone.utc).date()), help="last day, YYYY-MM-DD (default today)")
    ap.add_argument("--days", type=int, default=14)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args(argv)
    b = build(a.out, date.fromisoformat(a.end), a.days, a.seed)
    print(f"{LABEL}\n{b['events']} 6W events and {len(b['decisions']['nodes'])} decision-log items, "
          f"{a.days} days ending {a.end} -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
